def split_sql_statements(sql: str) -> list[str]:
    statements = []
    current = []
    in_single_quote = False
    in_double_quote = False
    in_line_comment = False
    in_block_comment = False
    dollar_quote_tag = None

    i = 0
    n = len(sql)
    while i < n:
        c = sql[i]

        # Handle line comments (-- ...) and block comments (/* ... */)
        if not in_single_quote and not in_double_quote and dollar_quote_tag is None:
            if not in_line_comment and not in_block_comment:
                if c == "-" and i + 1 < n and sql[i + 1] == "-":
                    in_line_comment = True
                    current.append(c)
                    i += 1
                    continue
                elif c == "/" and i + 1 < n and sql[i + 1] == "*":
                    in_block_comment = True
                    current.append(c)
                    i += 1
                    continue
            elif in_line_comment:
                if c == "\n":
                    in_line_comment = False
                current.append(c)
                i += 1
                continue
            elif in_block_comment:
                if c == "*" and i + 1 < n and sql[i + 1] == "/":
                    in_block_comment = False
                    current.append(c)
                    current.append("/")
                    i += 2
                    continue
                current.append(c)
                i += 1
                continue

        # Handle dollar quotes ($tag$...$tag$)
        if not in_line_comment and not in_block_comment and not in_single_quote and not in_double_quote:
            if dollar_quote_tag is None:
                if c == "$":
                    m = re.match(r"\$[A-Za-z0-9_]*\$", sql[i:])
                    if m:
                        dollar_quote_tag = m.group(0)
                        current.append(dollar_quote_tag)
                        i += len(dollar_quote_tag)
                        continue
            else:
                if sql[i:i + len(dollar_quote_tag)] == dollar_quote_tag:
                    current.append(dollar_quote_tag)
                    i += len(dollar_quote_tag)
                    dollar_quote_tag = None
                    continue
                current.append(c)
                i += 1
                continue

        # Handle single and double quotes
        if not in_line_comment and not in_block_comment and dollar_quote_tag is None:
            if c == "'" and not in_double_quote:
                if in_single_quote and i + 1 < n and sql[i + 1] == "'":
                    current.append("''")
                    i += 2
                    continue
                in_single_quote = not in_single_quote
            elif c == '"' and not in_single_quote:
                in_double_quote = not in_double_quote

        # Statement separator
        if (
            c == ";"
            and not in_single_quote
            and not in_double_quote
            and dollar_quote_tag is None
            and not in_line_comment
            and not in_block_comment
        ):
            stmt = "".join(current).strip()
            if stmt:
                statements.append(stmt)
            current = []
            i += 1
            continue

        current.append(c)
        i += 1

    last = "".join(current).strip()
    if last:
        statements.append(last)
    return statements


